<section>
    <h2>1. About SK 360&deg;</h2>
    <p>SK 360&deg; is a management and coordination system intended to support the Sangguniang Kabataan Federation of Lipa City and authorized SK officials. It provides tools for accounts, submissions, administrative review, meetings, records, and public information.</p>
</section>
<section>
    <h2>2. Information the System Handles</h2>
    <p>Depending on how you use SK 360&deg;, the system may handle:</p>
    <ul>
        <li>Account details such as your name, email address, phone number, barangay, role, account status, and profile photo.</li>
        <li>Authentication information, including your password credential and account setup or recovery information.</li>
        <li>Official records you submit or manage, including accomplishment reports, budget and financial documents, leadership details, and related files.</li>
        <li>Meeting schedules and participation or attendance records.</li>
        <li>Submission, review, ranking, notification, and other activity or status records produced by system workflows.</li>
        <li>For public portal feedback, a visitor's name, email address, and comment; verification-related records may also be processed when feedback is submitted.</li>
    </ul>
    <p>The system may also display selected official or organizational information publicly, such as published announcements, calendars, leadership information, and annual budget documents.</p>
</section>
<section>
    <h2>3. How Information Is Used</h2>
    <p>Information is used to manage and authenticate accounts; coordinate barangay SK activities; receive and review reports and budget documents; produce consolidations and archives; manage meetings and attendance; support system rankings and monitoring; deliver notifications; and operate public portal features such as announcement feedback.</p>
</section>
<section>
    <h2>4. Access and Submitted Documents</h2>
    <p>Access to official functions is based on the account's assigned role and the functions available to that role. Authorized SK 360&deg; officials may view and process submitted documents for system-related administrative purposes, including review, consolidation, and archiving. Information identified for public release may be available through the Public Portal.</p>
</section>
<section>
    <h2>5. Safeguarding Information</h2>
    <p>SK 360&deg; uses reasonable technical and administrative measures implemented within the system to help protect stored information. No specific security guarantee is made by this notice.</p>
</section>
<section>
    <h2>6. Retention</h2>
    <p>Records may be retained as part of current and archived administration-term records and system operations, subject to applicable organizational and legal requirements. This notice does not set a fixed retention period.</p>
</section>
<section>
    <h2>7. Your Responsibilities and Requests</h2>
    <p>Keep your login credentials private, use your own account, provide accurate account information, and submit only material relevant to official SK 360&deg; functions. You may request correction or clarification of your personal information through the appropriate SK 360&deg; administrator or SK Federation of Lipa City, subject to applicable rules and verification.</p>
    <p>SK 360&deg; is intended to handle personal information in accordance with applicable Philippine data privacy requirements, including Republic Act No. 10173, the Data Privacy Act of 2012. For general information, see the <a href="https://officialgazette.gov.ph/2012/08/15/republic-act-no-10173/" target="_blank" rel="noopener">Data Privacy Act of 2012</a>. This notice is not legal advice and does not represent a formal determination of compliance.</p>
</section>
